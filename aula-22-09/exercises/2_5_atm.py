# valor do saque e depois informar quantas notas de cada valor serão fornecidas. As notas
# disponíveis serão as de 10, 50, 100 e 200 reais. O valor mínimo é de 10 reais e o máximo
# de 1,000 reais. Apenas valores múltiplos de 10 são permitidos para saque. O programa
# não deve se preocupar com a quantidade de notas existentes na máquina.
# Ex.: Para sacar a quantia de 180 reais, o programa fornece uma nota de 100, uma nota
# de 50, uma nota de 20 e uma nota de 10.